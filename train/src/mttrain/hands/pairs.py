MAX_RESIDUAL_CM = 2.0  # contact anchors (fingertip on fingertip, palm on palm)
MAX_PLACE_CM = 3.0  # wrist and middle knuckle
# events whose contact depends on the palm direction; elsewhere the reached pose is simply the truth
PALM_CHECKED = {"palms", "rub", "clap", "steeple"}
MAX_OVERLAP_CM = 0.5  # deepest allowed capsule overlap anywhere in an event (touching is fine)
CONTACT_OVERLAP_CM = 2.5  # contact events before the collision relaxation (relax.Relaxer) resolves them
FINAL_OVERLAP_CM = 0.6  # after relaxation; sequences above it are regenerated by the callers
CONTACT = {"palms", "rub", "clap", "steeple", "tap", "count_on_hand"}  # retried with slack
ELBOW_W = 1.0
ORIENT = {0: 1.0, 9: 1.0, 5: 2.0, 17: 2.0}  # wrist, middle, index and little knuckle: weights
TIP = {"thumb": 4, "index": 8, "middle": 12, "ring": 16, "pinky": 20}
EVENTS = {"palms": 1.0, "steeple": 1.0, "tap": 1.0, "count_on_hand": 1.2, "rub": 0.8, "clap": 0.8, "cross": 1.0,
          "occlude": 1.0, "approach": 1.0, "turn": 1.2, "wrist": 1.0}


def _unit(v):
    return v / np.linalg.norm(v)


# measured from the forearm axis to the wrist -> middle knuckle line: MHR's seated rest postures already read
# up to ~23 deg toward the thumb (the middle metacarpal is not in line with the forearm), so the bounds sit
# around that; they still block the extreme bends MHR's own limits allow (up to ~125 deg)
WRIST_FLEX = (-80.0, 90.0)  # extension .. flexion (toward the palm), deg
WRIST_DEV = (-45.0, 40.0)  # toward the little finger .. toward the thumb, deg


def hand_axes(P, side):
    """21 hand points -> unit (d along the hand, t toward the thumb, n palm normal: the side fingers curl to)."""
    d = _unit(P[9] - P[0])
    t = P[5] - P[17]
    t = _unit(t - (t @ d) * d)
    n = np.cross(d, t) * (1.0 if side == "l" else -1.0)
    return d, t, n


def forearm_angles(f, d, t, n):
    """Wrist flexion and deviation (deg) from the forearm direction f (elbow -> wrist, unit, (..., 3)) in the hand's
    frame (d along the hand, t toward the thumb, n palm normal). A hand flexed by a toward the palm sees the forearm
    at cos(a) d - sin(a) n; deviated by b toward the thumb, at cos(b) d - sin(b) t. Well-conditioned at any bend
    (the knuckle axis t stays perpendicular to the flexion plane)."""
    fd, ft, fn = f @ d, f @ t, f @ n
    return np.degrees(np.arctan2(-fn, fd)), np.degrees(np.arcsin(np.clip(-ft, -1, 1)))


def wrist_angles(elbow, P, side):
    """Wrist flexion and deviation (deg) of the hand points P against the forearm (elbow -> wrist)."""
    d, t, n = hand_axes(P, side)
    return forearm_angles(_unit(P[0] - elbow), d, t, n)


def best_elbow(S, W, d, t, n, U, L, up, fwd, n_samples=96):
    """Elbow position for a hand at wrist W (hand axes d, t, n) and shoulder S, upper arm U, forearm L (cm):
    on the circle of reachable elbows, the point giving the most natural wrist (least sideways bend, flexion
    in range, elbow not above the shoulder or behind the body). -> (elbow, flex, dev) or None if the wrist is
    out of reach or no point gives an anatomically possible wrist."""
    D = np.linalg.norm(W - S)
    if D >= U + L - 0.5 or D <= abs(U - L) + 0.5:
        return None
    axis = (W - S) / D
    a = (U * U - L * L + D * D) / (2 * D)
    r = np.sqrt(max(U * U - a * a, 0.0))
    c = S + axis * a
    u1 = _unit(np.cross(axis, up) if abs(axis @ up) < 0.95 else np.cross(axis, fwd))
    u2 = np.cross(axis, u1)
    phi = np.linspace(0, 2 * np.pi, n_samples, endpoint=False)
    E = c + r * (np.cos(phi)[:, None] * u1 + np.sin(phi)[:, None] * u2)
    f = (W - E) / np.linalg.norm(W - E, axis=1, keepdims=True)
    flex, dev = forearm_angles(f, d, t, n)
    ok = (flex >= WRIST_FLEX[0]) & (flex <= WRIST_FLEX[1]) & (dev >= WRIST_DEV[0]) & (dev <= WRIST_DEV[1])
    if not ok.any():
        return None
    above = np.maximum((E - S) @ up, 0.0)  # elbow above the shoulder
    behind = np.maximum(-((E - S) @ fwd) - 5.0, 0.0)  # elbow far behind the shoulder
    cost = (dev / 10.0) ** 2 + (above / 5.0) ** 2 + (behind / 5.0) ** 2 + np.where(ok, 0.0, 1e6)
    k = int(np.argmin(cost))
    return E[k], float(flex[k]), float(dev[k]), float(cost[k])


def still_head(mp, pn):
    """Hold neck and head at their first-frame pose (in place)."""
    idx = [k for k, n in enumerate(pn) if n.startswith(("neck_", "head_"))]
    mp[:, idx] = mp[0, idx]


def mirror_lat(v, lat):
    return v - 2 * (v @ lat) * lat


def _rotate(v, axis, ang):
    """Rodrigues: v rotated by ang (rad) about the unit axis."""
    axis = _unit(axis)
    return v * np.cos(ang) + np.cross(axis, v) * np.sin(ang) + axis * (axis @ v) * (1 - np.cos(ang))


class PairChoreo:
    def __init__(self, ch, lm, pn, limits, hm=None):
        self.ch, self.lm, self.pn, self.limits = ch, lm, pn, limits
        self.jn = list(ch.skeleton.joint_names)
        self.P = {n: i for i, n in enumerate(pn)}
        self.hm = hm or HandMotion()
        self.lib = self.hm.library
        self.arm = {s: [self.P[f"{s}_{k}"] for k in ARM_KEYS] for s in "lr"}
        self.fing = {s: self.hm.fk.idx[s] for s in "lr"}
        self._off = {}
        self.body = np.zeros(len(pn), np.float32)  # scale parameters of the current body (generate sets it)
        self.forearm, self.upper_arm = 25.0, 30.0  # cm, set from the body in set_body
        self._body = None  # (shoulders, left, up, forward) of the current key's body frame
        self.collider = Collider(ch)
        from .relax import Relaxer
        self.relaxer = Relaxer(ch)
        self.last_overlap = 0.0  # deepest overlap left in the last generated sequence (cm)
        from collections import Counter
        self.rejects = Counter()  # why key poses were rejected (diagnostics)
        q = self.lib["flat_together"].copy()
        pts = self.hm.fk.points(q)
        self.flat_palm = self.hm.solve_thumb(q, pts[5] + (np.array([1.5, 1.8, 0.0]) / 100.0) @ self.hm.R)  # thumb in the palm plane

    # --- hand placement ----------------------------------------------------------------------------
    def offsets(self, q, side):
        """The hand's 21 points (cm) in its own frame rows (fwd, thumbward-ish, palm-ish) for finger pose q,
        on the current body's proportions (hand size scales with the body)."""
        key = (side, q.tobytes(), self.body.tobytes())
        if key not in self._off:
            from mtcore.mhr import positions
            Pm = positions(self.ch, self.hm.fk.full(q, side, base=self.body))[self.hm.fk.mp21[side]]
            w, R = hand_frame(Pm)
            self._off[key] = (Pm - w) @ R.T
        return self._off[key]

    def place(self, q, side, d, n, anchor, at):
        """World points (21, 3) cm of a hand with finger pose q, along d, palm normal n, point `anchor` at `at`.
        The right hand is the left mirrored: its frame's side and third rows flip (skeleton.hand_frame)."""
        s = 1.0 if side == "l" else -1.0
        d = _unit(d)
        n = _unit(n - (n @ d) * d)
        A = np.stack([d, s * np.cross(n, d), s * n])
        O = self.offsets(q, side)
        W = at - O[anchor] @ A
        return W + O @ A

    def constraints(self, side, pts, anchor=None, elbow=None):
        tg = [(f"{side}_{MP21[k]}", pts[k], w, k in (0, 9)) for k, w in ORIENT.items()]
        if elbow is not None:  # reachable elbow giving a natural wrist (best_elbow)
            tg.append((f"{side}_lowarm", elbow, ELBOW_W, False))
        if anchor is not None and anchor not in ORIENT:
            tg.append((f"{side}_{MP21[anchor]}", pts[anchor], 3.0, True))
        return tg

    # --- events ------------------------------------------------------------------------------------
    def _frame(self, X):
        sh, lat, up, fwd = choreo._body_frame(X)
        return sh, lat, up, fwd

    def _g(self, name):
        return self.lib[name].copy()

    def event(self, rng, kind, X, slack=0.0):
        """A list of keys: (move s, hold s, {side: (q, d, n, anchor, at)}). slack (cm): contacts that far apart."""
        sh, lat, up, fwd = self._frame(X)
        self._body = (sh, lat, up, fwd)
        C = sh + fwd * rng.uniform(25, 40) - up * rng.uniform(8, 25) + lat * rng.uniform(-5, 5)
        keys = []
        tilt = lambda: fwd * rng.uniform(-0.2, 0.4)
        if kind in ("palms", "rub", "clap"):
            q = self.flat_palm.copy()
            d = _unit(up + fwd * 0.5)
            C = sh + fwd * rng.uniform(22, 32) - up * rng.uniform(15, 25) + lat * rng.uniform(-3, 3)
            touch = 2.6 + slack

            def palms(gap, shift=0.0):
                def follow(act):  # right hand: the left one's actual pose reflected across its palm plane
                    dl, _, nl = hand_axes(act["l"], "l")
                    return (q, dl, -nl, 9, act["l"][9] + nl * gap - up * 2 * shift)
                return {"l": (q, d, -lat, 9, C + lat * gap / 2 + up * shift, 50.0), "r": follow}
            keys.append((rng.uniform(0.5, 1.0), rng.uniform(0.6, 2.0), palms(touch)))
            if kind == "rub":
                for k in range(int(rng.integers(4, 9))):
                    keys.append((0.25, 0.0, palms(touch, 3.0 * (1 if k % 2 else -1))))
            if kind == "clap":
                for _ in range(int(rng.integers(3, 6))):
                    keys.append((0.18, 0.05, palms(rng.uniform(14, 22))))
                    keys.append((0.15, 0.08, palms(touch)))
        elif kind == "steeple":
            q = self._g("relaxed")
            d_l = _unit(up + fwd * 0.3 - lat * 0.35)

            def follow(act):
                dl, _, nl = hand_axes(act["l"], "l")
                return (q, mirror_lat(dl, lat), mirror_lat(nl, lat), 12, act["l"][12] - lat * (1.7 + slack))
            keys.append((rng.uniform(0.6, 1.0), rng.uniform(0.8, 2.0),
                         {"l": (q, d_l, -lat, 12, C + lat * (0.85 + slack / 2), 30.0), "r": follow}))
        elif kind in ("tap", "approach"):
            q = self._g("point")
            n_l = _unit(-up + fwd * rng.uniform(-0.5, 0.5))
            d_l = _unit(-lat + fwd * 0.15)

            def far(g):
                def follow(act):
                    dl, _, nl = hand_axes(act["l"], "l")
                    return (q, mirror_lat(dl, lat), mirror_lat(nl, lat), 8, act["l"][8] - lat * g)
                return {"l": (q, d_l, n_l, 8, C + lat * g / 2), "r": follow}
            keys.append((rng.uniform(0.6, 1.0), rng.uniform(0.3, 0.8), far(rng.uniform(12, 20))))
            if kind == "tap":
                for _ in range(int(rng.integers(2, 5))):
                    keys.append((0.2, 0.05, far(1.7 + slack)))
                    keys.append((0.2, 0.05, far(rng.uniform(4, 8))))
            else:
                keys.append((rng.uniform(1.2, 2.5), rng.uniform(0.3, 1.0), far(rng.uniform(2.2, 3.5) + slack)))
                keys.append((rng.uniform(0.8, 1.5), 0.3, far(rng.uniform(14, 22))))
        elif kind == "count_on_hand":
            passive = "l" if rng.random() < 0.5 else "r"
            active = "r" if passive == "l" else "l"
            sp = 1.0 if passive == "l" else -1.0
            qp, qa = self._g("open"), self._g("point")
            Wp = C + lat * sp * rng.uniform(2, 8) + up * rng.uniform(0, 8)
            dp = _unit(up + fwd * rng.uniform(0.3, 0.8) + lat * (-sp) * 0.2)  # tilted forward: reachable with a natural wrist
            np_ = _unit(fwd + lat * (-sp) * rng.uniform(0.0, 0.6))  # palm toward the camera, turned in a little
            spec_p = (qp, dp, np_, 0, Wp, 50.0)

            def touch(f):
                def follow(act):  # the index tip onto the passive hand's actual fingertip, from its palm side
                    P = act[passive]
                    _, _, n_pa = hand_axes(P, passive)
                    da = _unit(-n_pa * 0.8 + up * 0.3 + lat * sp * 0.3)
                    na = _unit(-up + fwd * 0.3 - (-up + fwd * 0.3) @ da * da)
                    off = 6.0 if f is None else 1.6 + slack
                    return (qa, da, na, 8, P[TIP[f or "middle"]] + n_pa * off, 40.0)
                return {passive: spec_p, active: follow}
            fingers = ["thumb", "index", "middle", "ring", "pinky"]
            if rng.random() < 0.5:
                fingers = fingers[::-1]
            keys.append((rng.uniform(0.6, 1.0), 0.3, touch(None)))
            for f in fingers:
                keys.append((rng.uniform(0.3, 0.5), rng.uniform(0.15, 0.4), touch(f)))
        elif kind == "cross":
            front = 1.0 if rng.random() < 0.5 else -1.0
            for _ in range(int(rng.integers(1, 3))):
                ql, qr = (self.lib[self.hm.names[rng.choice(len(self.hm.names), p=self.hm.gesture_p)]] for _ in range(2))
                d = _unit(up + fwd * 0.2)
                off = rng.uniform(4, 12)
                face = fwd if rng.random() < 0.6 else -fwd  # palms to the camera or to the body
                keys.append((rng.uniform(0.6, 1.0), rng.uniform(0.5, 1.5),
                             {"l": (ql, d, face, 0, C - lat * off - up * 6 + fwd * 4 * front, 70.0),
                              "r": (qr, d, face, 0, C + lat * off - up * 6 - fwd * 4 * front, 70.0)}))
                keys.append((rng.uniform(0.5, 0.9), rng.uniform(0.2, 0.6),
                             {"l": (ql, d, face, 0, C + lat * off - up * 6, 70.0), "r": (qr, d, face, 0, C - lat * off - up * 6, 70.0)}))
                front = -front
        elif kind == "occlude":
            front_side = "l" if rng.random() < 0.5 else "r"
            q1, q2 = self._g("open"), self._g("relaxed")
            d = _unit(up + fwd * 0.1)
            x0, x1 = rng.uniform(-14, -6), rng.uniform(6, 14)
            if rng.random() < 0.5:
                x0, x1 = x1, x0
            back = "r" if front_side == "l" else "l"
            Wb = C - up * 6
            spec_b = (q2, d, fwd, 0, Wb, 60.0)
            keys.append((rng.uniform(0.6, 1.0), 0.3, {back: spec_b, front_side: (q1, d, fwd, 0, Wb + fwd * 9 + lat * x0, 60.0)}))
            keys.append((rng.uniform(1.2, 2.5), 0.3, {back: spec_b, front_side: (q1, d, fwd, 0, Wb + fwd * 9 + lat * x1, 60.0)}))
        elif kind == "turn":
            side = "l" if rng.random() < 0.5 else "r"
            sg = 1.0 if side == "l" else -1.0
            q = self._g(["open", "relaxed", "point", "flat_together"][rng.integers(4)])
            W = sh + fwd * rng.uniform(25, 40) - up * rng.uniform(5, 25) + lat * sg * rng.uniform(5, 22)
            d = _unit(up * rng.uniform(0.4, 1.0) + fwd * rng.uniform(0.0, 0.6) - lat * sg * 0.2)
            a = _unit(np.cross(d, up if abs(d @ up) < 0.9 else fwd))
            n0 = _unit(fwd - (fwd @ d) * d)
            fast = rng.random() < 0.5
            for k in range(int(rng.integers(2, 5))):
                n = n0 if k % 2 == 0 else -n0
                keys.append((rng.uniform(0.25, 0.45) if fast else rng.uniform(0.7, 1.2), rng.uniform(0.2, 0.8),
                             {side: (q, d, n, 0, W)}))
        elif kind == "wrist":
            side = "l" if rng.random() < 0.5 else "r"
            sg = 1.0 if side == "l" else -1.0
            q = self._g(["open", "relaxed", "flat_together"][rng.integers(3)])
            W = sh + fwd * rng.uniform(25, 40) - up * rng.uniform(5, 25) + lat * sg * rng.uniform(5, 22)
            d0 = _unit(up + fwd * 0.3 - lat * sg * 0.2)
            n0 = _unit(fwd - (fwd @ d0) * d0)
            t = np.cross(n0, d0)
            for k in range(int(rng.integers(3, 6))):
                ang = np.radians(rng.uniform(25, 60)) * (1 if k % 2 else -1)
                axis = t if rng.random() < 0.6 else n0  # flex/extend (about the knuckle line), or side to side
                d, n = _rotate(d0, axis, ang), _rotate(n0, axis, ang)
                keys.append((rng.uniform(0.4, 0.8), rng.uniform(0.1, 0.5), {side: (q, d, n, 0, W)}))
        return keys

    def neutral(self, rng, X, side):
        """A loose hand pose in front of the chest (between events)."""
        sh, lat, up, fwd = self._frame(X)
        self._body = (sh, lat, up, fwd)
        sg = 1.0 if side == "l" else -1.0
        W = sh + fwd * rng.uniform(20, 38) - up * rng.uniform(12, 30) + lat * sg * rng.uniform(4, 20)
        d = _unit(up * rng.uniform(0.2, 1.0) + fwd * rng.uniform(0.0, 0.8) - lat * sg * rng.uniform(0.0, 0.5))
        a = _unit(np.cross(d, fwd))
        phi = rng.uniform(0, 2 * np.pi)
        n = np.cos(phi) * a + np.sin(phi) * np.cross(d, a)
        return (self.hm.key_pose(rng)[0], d, n, 0, W)

    # --- sequences ---------------------------------------------------------------------------------
    def set_body(self, body):
        """Body proportions (scale parameters) for hand geometry and the forearm length."""
        from mtcore.mhr import positions
        self.body = np.asarray(body, np.float32)
        P = positions(self.ch, self.body[None])[0]
        self.forearm = float(np.linalg.norm(P[self.jn.index("l_lowarm")] - P[self.jn.index("l_wrist")]))
        self.upper_arm = float(np.linalg.norm(P[self.jn.index("l_uparm")] - P[self.jn.index("l_lowarm")]))

    def _points(self, m, side):
        from mtcore.mhr import positions
        P = positions(self.ch, m[None].astype(np.float32))[0]
        return P[self.hm.fk.mp21[side]], P[self.jn.index(f"{side}_lowarm")]

    def _solve(self, mp_k, specs, palm_check=False):
        """IK per hand at body pose mp_k (P,): concrete specs first, then `follow` specs computed from the solved
        hands' actual points. -> {side: (arm parameters, finger q)} or None (missed target, palm direction,
        anatomically impossible wrist)."""
        m0 = mp_k.copy()
        order = [s for s in specs if not callable(specs[s])] + [s for s in specs if callable(specs[s])]
        result, actual = {}, {}
        self.chosen = {}
        for side in order:
            spec = specs[side]
            if callable(spec):
                spec = spec(actual)
            q, d, n, anchor, at = spec[:5]
            roll = spec[5] if len(spec) > 5 else 0.0
            m0[self.fing[side]] = q
            from mtcore.mhr import positions
            J = positions(self.ch, m0[None].astype(np.float32))[0]
            _, lat_b, up_b, fwd_b = self._body
            n_u = _unit(n - (n @ _unit(d)) * _unit(d))
            best = None
            # the finger direction may roll about the palm normal within +-roll: pick the most natural arm
            for r_deg in (np.linspace(-roll, roll, 9) if roll else [0.0]):
                dd = _rotate(_unit(d), n_u, np.radians(r_deg))
                pp = self.place(q, side, dd, n_u, anchor, at)
                hd, ht, hn = hand_axes(pp, side)
                el = best_elbow(J[self.jn.index(f"{side}_uparm")], pp[0], hd, ht, hn, self.upper_arm, self.forearm, up_b, fwd_b)
                if el is not None and (best is None or el[3] < best[1][3]):
                    best = (dd, el, pp)
            if best is None:
                self.rejects["anatomy"] += 1
                return None
            d, el, pts = best[0], best[1], best[2]
            n = n_u
            spec = (q, d, n, anchor, at)
            tg = self.constraints(side, pts, anchor, el[0])
            if callable(specs[side]) or roll:
                self.chosen[side] = (d, n)
            sol = choreo._solve(self.ch, self.pn, self.jn, m0, (side,), tg)
            prim = [(j, p) for j, p, _, pr in tg if pr]
            res = np.linalg.norm(choreo._joint_pos(self.ch, sol, [j for j, _ in prim], self.jn)
                                 - np.stack([p for _, p in prim]), axis=-1)
            limit = np.array([MAX_PLACE_CM if j.endswith(("_wrist", "_middle1")) else MAX_RESIDUAL_CM for j, _ in prim])
            if (res > limit).any():
                self.rejects["target"] += 1
                return None
            m0[self.arm[side]] = sol[self.arm[side]]
            P, elbow = self._points(m0, side)
            flex, dev = wrist_angles(elbow, P, side)
            if not (WRIST_FLEX[0] <= flex <= WRIST_FLEX[1] and WRIST_DEV[0] <= dev <= WRIST_DEV[1]):
                self.rejects["wrist"] += 1
                return None
            if palm_check:
                want = pts
                if np.degrees(np.arccos(np.clip(hand_axes(P, side)[2] @ hand_axes(want, side)[2], -1, 1))) > MAX_PALM_DEG:
                    self.rejects["palm"] += 1
                    return None
            result[side] = (sol[self.arm[side]], q)
            actual[side] = P
        return result

    def _blend(self, keys, T):
        """Key lists per side -> arm parameters (T, n) and finger parameters (T, 27) per side (no idle motion)."""
        frames = np.arange(T)
        out = {}
        for s in "lr":
            arm = np.repeat(keys[s][0][2][None], T, 0)
            fq = np.repeat(keys[s][0][3][None], T, 0)
            for (a, b, pa, qa), (_, _, pp, qp) in zip(keys[s][1:], keys[s][:-1]):
                u = min_jerk(np.clip((frames - a) / max(1, b - a), 0, 1))
                after = frames >= a
                arm[after] = pp + (pa - pp) * u[after, None]
                fq[after] = qp + (qa - qp) * u[after, None]
            out[s] = (arm, fq)
        return out

    def _clear(self, mp, keys, T, f0, f1, tol=MAX_OVERLAP_CM):
        """Do the hands stay apart (overlap <= tol cm) over frames f0..f1 with these keys?"""
        f1 = min(f1, T - 1)
        if f1 <= f0:
            return True
        b = self._blend(keys, T)
        win = mp[f0:f1 + 1:2].copy()
        for s in "lr":
            win[:, self.arm[s]] = b[s][0][f0:f1 + 1:2]
            win[:, self.fing[s]] = b[s][1][f0:f1 + 1:2]
        return self.collider.penetration(win)[0].max() <= tol

    def generate(self, rng, base, T, fps):
        """-> model parameters (T, P) with arms and fingers, segments [{label, variant, t0, t1} ms]. Every
        accepted step (moves between events, events) is checked for interpenetration over its frames."""
        pn = self.pn
        body = np.where([n.startswith("scale_") for n in pn], base, 0.0)
        self.set_body(body)
        pair = tuple(rng.choice(["lap", "desk"], 2))
        mp = seat(rng, pn, np.repeat(body[None], T, 0), fps, self.limits, force_rest=pair, moves=False)
        still_head(mp, pn)
        keys = {s: [(0, 0, mp[0, self.arm[s]].copy(), np.zeros(len(PARAMS)))] for s in "lr"}
        segs = []
        k = int(rng.uniform(0.3, 1.0) * fps)
        cur = {s: (mp[0, self.arm[s]].copy(), np.zeros(len(PARAMS))) for s in "lr"}
        names, w = list(EVENTS), np.array(list(EVENTS.values()))
        while k < T - int(1.0 * fps):
            m = mp[min(k, T - 1)].copy()
            for s in "lr":
                m[self.arm[s]] = cur[s][0]
            X = self.lm(skeleton_state(self.ch, m)[None])[0]
            # between events: both hands to loose neutral poses (a few tries to find a clear move)
            for _ in range(3):
                sol = self._solve(m, {s: self.neutral(rng, X, s) for s in "lr"})
                if not sol:
                    continue
                end = min(T - 1, k + int(rng.uniform(0.6, 1.0) * fps))
                trial = {s: keys[s] + [(k, end, *sol[s])] for s in "lr"}
                if self._clear(mp, trial, T, k, end):
                    keys, cur = trial, {s: sol[s] for s in "lr"}
                    k = end + int(rng.uniform(0.2, 1.0) * fps)
                    break
            kind = names[rng.choice(len(names), p=w / w.sum())]
            accepted = None
            for attempt in range(3):
                slack = float(attempt) if kind in CONTACT else 0.0
                spec_keys = self.event(rng, kind, X, slack)
                sols = [self._solve(m, specs, kind in PALM_CHECKED) for _, _, specs in spec_keys]
                if not all(sols):
                    continue
                trial, kk, c = {s: list(keys[s]) for s in "lr"}, k, dict(cur)
                for (move, hold, _), sol in zip(spec_keys, sols):
                    end = min(T - 1, kk + max(1, int(move * fps)))
                    for s, v in sol.items():
                        trial[s].append((kk, end, *v))
                        c[s] = v
                    kk = end + int(hold * fps)
                    if kk >= T - 1:
                        break
                if self._clear(mp, trial, T, k, kk, CONTACT_OVERLAP_CM if kind in CONTACT else MAX_OVERLAP_CM):
                    accepted = (trial, kk, c)
                    break
            if accepted is None:
                k += int(0.5 * fps)  # nothing clear: let the hands rest a moment
                continue
            t0 = k
            keys, k, cur = accepted
            segs.append({"label": "pair" if kind not in ("turn", "wrist") else kind, "variant": kind,
                         "t0": round(t0 / fps * 1000, 1), "t1": round(min(k, T - 1) / fps * 1000, 1)})
        out = mp.copy()
        t = np.arange(T) / fps
        b = self._blend(keys, T)
        for s in "lr":
            out[:, self.arm[s]] = b[s][0]
            fq = np.clip(b[s][1] + self.hm._idle(rng, t), self.hm.lo, self.hm.hi)
            fq[:, [PARAMS.index(p) for p in UNOBSERVABLE]] = 0.0
            out[:, self.fing[s]] = fq
        out = clamp(pn, out, self.limits)
        out, _, after = self.relaxer(out)  # fingers (and a little of the wrists) pushed out of each other
        self.last_overlap = float(after.max())
        return out, segs
