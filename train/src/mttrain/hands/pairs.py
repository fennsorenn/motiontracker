    def set_pose(self, m):
        """The body pose keys are being solved at (body capsules for clearance and the elbow search)."""
        self.caps_now = self.collider.body_capsules(m)
        self.thighs_now = {s: self.collider.capsules_at(m, (f"{s}_upleg",)) for s in "lr"}
        self.mesh.set_pose(m)

    def lift(self, m, side, tries=5, extra=0.5, max_cm=6.0):
        """Arm `side` of pose m (P,) pushed out of the skin by IK: while a hand point is closer than MESH_HAND_CM +
        extra, or a forearm point closer than MESH_FORE_CM + extra, the hand moves along the skin normal at the
        deepest point by the deficit, at most max_cm in all (what still clips is left to the mesh check to
        reject). Changes m in place."""
        from mtcore.mhr import positions
        u = np.linspace(0.15, 0.9, 5)
        r_fore = MESH_FORE_CM[0] + (MESH_FORE_CM[1] - MESH_FORE_CM[0]) * u
        total = 0.0
        for _ in range(tries):
            P = positions(self.ch, m[None].astype(np.float32))[0]
            H = P[self.hm.fk.mp21[side]]
            E, W = P[self.jn.index(f"{side}_lowarm")], P[self.jn.index(f"{side}_wrist")]
            pts = np.concatenate([H, E + (W - E) * u[:, None]])
            deficit = np.concatenate([np.full(len(H), MESH_HAND_CM), r_fore]) + extra - self.mesh.distance(pts)
            k = int(np.argmax(deficit))
            if deficit[k] <= 0 or total >= max_cm:
                return m
            step = min(deficit[k] + 0.3, max_cm - total)
            total += step
            shift = self.mesh.normal(pts[k]) * step
            tg = [(f"{side}_{MP21[j]}", H[j] + shift, w, j in (0, 9)) for j, w in ORIENT.items()]
            sol = choreo._solve(self.ch, self.pn, self.jn, m, (side,), tg)
            m[self.arm[side]] = sol[self.arm[side]]
        return m

    def thigh_spec(self, rng, X, side, q):
        """Key spec of a hand with finger pose q lying on its thigh (mesh surface), or None."""
        sh, lat, up, fwd = choreo._body_frame(X)
        hip, knee = X[23 if side == "l" else 24], X[25 if side == "l" else 26]
        sg = 1.0 if side == "l" else -1.0
        along = knee - hip
        at = self.mesh.surface(hip + along * rng.uniform(0.35, 0.75) + up * 25.0, up, rng.uniform(*BODY_CONTACT_CLEAR_CM))
        if at is None:
            return None
        k_dir = _unit(along - (along @ up) * up)
        d = _unit(k_dir - lat * sg * rng.uniform(0.0, 0.5) - up * rng.uniform(0.0, 0.3))
        n = _unit(-up + lat * sg * rng.uniform(-0.2, 0.4))
        return (q, d, n, 9, self.on_skin(q, side, d, n, at, up), 30.0)

    def fix_rest(self, m, rng=None):
        """Resting arms (seated rest templates, solved on MHR's template body) lifted out of this body's skin:
        on heavier bodies the hands sat 2-3 cm inside the thighs (`lift`). -> m (P,)."""
        m = np.asarray(m, np.float64).copy()
        rng = rng if rng is not None else np.random.default_rng(0)
        self.set_pose(m)
        X = self.lm(skeleton_state(self.ch, m)[None])[0]
        self._body = choreo._body_frame(X)
        for side in "lr":
            self.lift(m, side, tries=10, max_cm=9.0)
            if self.mesh_clear(m[None], (side,)):
                continue
            # still inside (lap template far off this body): the hand laid on the thigh instead, fingers as they are
            self.body_slack = BODY_CONTACT_SLACK_CM
            for _ in range(4):
                spec = self.thigh_spec(rng, X, side, m[self.fing[side]].copy())
                sol = self._solve(m, {side: spec}) if spec is not None else None
                if sol is None:
                    continue
                trial = m.copy()
                trial[self.arm[side]] = sol[side][0]
                if self.mesh_clear(trial[None], (side,)):
                    m = trial
                    break
            self.body_slack = 0.0
        self.prev = {}
        return m

    def on_skin(self, q, side, d, n, at, out):
        """Lift a hand placed with its middle knuckle at `at` along `out` until no hand point is closer than
        MESH_HAND_CM + 1.2 cm to the skin (curled fingers, palm curvature, the IK's residual)."""
        for _ in range(6):
            need = (MESH_HAND_CM + 1.2) - self.mesh.distance(self.place(q, side, d, n, 9, at)).min()  # + the IK's residual
            if need <= 0:
                break
            at = at + _unit(out) * (need + 0.2)
        return at

    def forward_clear(self, C, fwd, need=9.0):
        """Move point C forward until it is `need` cm clear of the body (bellies differ between bodies)."""
        if self.caps_now is None:
            return C
        for _ in range(25):
            if body_clearance(C, self.caps_now) >= need and self.mesh.distance(C) >= 6.0:
                break
            C = C + fwd
        return C

    def set_body(self, body):
        """Body proportions (scale parameters) for hand geometry and the forearm length."""
        from mtcore.mhr import positions
        self.body = np.asarray(body, np.float32)
        P = positions(self.ch, self.body[None])[0]
        self.forearm = float(np.linalg.norm(P[self.jn.index("l_lowarm")] - P[self.jn.index("l_wrist")]))
        self.upper_arm = float(np.linalg.norm(P[self.jn.index("l_uparm")] - P[self.jn.index("l_lowarm")]))

    def _points(self, m, side):
        from mtcore.mhr import positions
        P = positions(self.ch, m[None].astype(np.float32))[0]
        return P[self.hm.fk.mp21[side]], P[self.jn.index(f"{side}_lowarm")]

    def _solve(self, mp_k, specs, palm_check=False):
        """IK per hand at body pose mp_k (P,): concrete specs first, then `follow` specs computed from the solved
        hands' actual points. -> {side: (arm parameters, finger q)} or None (missed target, palm direction,
        anatomically impossible wrist)."""
        m0 = mp_k.copy()
        order = [s for s in specs if not callable(specs[s])] + [s for s in specs if callable(specs[s])]
        result, actual = {}, {}
        self.chosen = {}
        for side in order:
            spec = specs[side]
            if callable(spec):
                try:
                    spec = spec({**actual, "prev": self.prev})
                except KeyError:  # builds on a hand that was not solved (an earlier key failed)
                    self.rejects["missing"] += 1
                    return None
            q, d, n, anchor, at = spec[:5]
            roll = spec[5] if len(spec) > 5 else 0.0
            m0[self.fing[side]] = q
            from mtcore.mhr import positions
            J = positions(self.ch, m0[None].astype(np.float32))[0]
            _, lat_b, up_b, fwd_b = self._body
            n_u = _unit(n - (n @ _unit(d)) * _unit(d))
            best = None
            # the finger direction may roll about the palm normal within +-roll: pick the most natural arm
            for r_deg in (np.linspace(-roll, roll, 9) if roll else [0.0]):
                dd = _rotate(_unit(d), n_u, np.radians(r_deg))
                pp = self.place(q, side, dd, n_u, anchor, at)
                hd, ht, hn = hand_axes(pp, side)
                el = best_elbow(J[self.jn.index(f"{side}_uparm")], pp[0], hd, ht, hn, self.upper_arm, self.forearm, up_b, fwd_b,
                                body=self.caps_now, body_slack=self.body_slack,
                                mesh=self.mesh if self.mesh.tree is not None else None)
                if el is not None and (best is None or el[3] < best[1][3]):
                    best = (dd, el, pp)
            if best is None:
                self.rejects["anatomy"] += 1
                return None
            d, el, pts = best[0], best[1], best[2]
            n = n_u
            spec = (q, d, n, anchor, at)
            tg = self.constraints(side, pts, anchor, el[0])
            if callable(specs[side]) or roll:
                self.chosen[side] = (d, n)
            sol = choreo._solve(self.ch, self.pn, self.jn, m0, (side,), tg)
            prim = [(j, p) for j, p, _, pr in tg if pr]
            res = np.linalg.norm(choreo._joint_pos(self.ch, sol, [j for j, _ in prim], self.jn)
                                 - np.stack([p for _, p in prim]), axis=-1)
            limit = np.array([MAX_PLACE_CM if j.endswith(("_wrist", "_middle1")) else MAX_RESIDUAL_CM for j, _ in prim])
            if (res > limit).any():
                self.rejects["target"] += 1
                return None
            m0[self.arm[side]] = sol[self.arm[side]]
            if self.body_slack > 0:  # hands resting on the body: off the skin despite the IK's residual
                self.lift(m0, side, extra=0.3, max_cm=4.0)
                sol = m0.copy()
            P, elbow = self._points(m0, side)
            flex, dev = wrist_angles(elbow, P, side)
            if not (WRIST_FLEX[0] <= flex <= WRIST_FLEX[1] and WRIST_DEV[0] <= dev <= WRIST_DEV[1]):
                self.rejects["wrist"] += 1
                return None
            if palm_check:
                want = pts
                if np.degrees(np.arccos(np.clip(hand_axes(P, side)[2] @ hand_axes(want, side)[2], -1, 1))) > MAX_PALM_DEG:
                    self.rejects["palm"] += 1
                    return None
            result[side] = (sol[self.arm[side]], q)
            actual[side] = P
        self.prev = {**self.prev, **{s_: (actual[s_], self._points(m0, s_)[1]) for s_ in actual}}
        return result

    def _blend(self, keys, T):
        """Key lists per side -> arm parameters (T, n) and finger parameters (T, 27) per side (no idle motion)."""
        frames = np.arange(T)
        out = {}
        for s in "lr":
            arm = np.repeat(keys[s][0][2][None], T, 0)
            fq = np.repeat(keys[s][0][3][None], T, 0)
            for (a, b, pa, qa), (_, _, pp, qp) in zip(keys[s][1:], keys[s][:-1]):
                u = min_jerk(np.clip((frames - a) / max(1, b - a), 0, 1))
                after = frames >= a
                arm[after] = pp + (pa - pp) * u[after, None]
                fq[after] = qp + (qa - qp) * u[after, None]
            out[s] = (arm, fq)
        return out

    def _clear(self, mp, keys, T, f0, f1, tol=MAX_OVERLAP_CM, body_tol=0.0):
        """Do the hands stay apart (overlap <= tol cm) over frames f0..f1 with these keys?"""
        f1 = min(f1, T - 1)
        if f1 <= f0:
            return True
        b = self._blend(keys, T)
        win = mp[f0:f1 + 1:2].copy()
        for s in "lr":
            win[:, self.arm[s]] = b[s][0][f0:f1 + 1:2]
            win[:, self.fing[s]] = b[s][1][f0:f1 + 1:2]
        arm, body = self.collider.penetration(win)
        if not (arm.max() <= tol and body.max() <= body_tol):
            return False
        return self.mesh_clear(win)

    def mesh_clip_frames(self, mp):
        """Per frame of mp (T, P): does a hand point or forearm come closer to the skin than MESH_HAND_CM /
        MESH_FORE_CM (mesh at its current pose)? -> (T,) bool."""
        from mtcore.mhr import positions
        P = positions(self.ch, np.asarray(mp, np.float32))
        u = np.linspace(0.15, 0.9, 5)
        r_fore = MESH_FORE_CM[0] + (MESH_FORE_CM[1] - MESH_FORE_CM[0]) * u
        bad = np.zeros(len(mp), bool)
        for s_ in "lr":
            bad |= (self.mesh.distance(P[:, self.hm.fk.mp21[s_]]) < MESH_HAND_CM).any(1)
            E, W = P[:, self.jn.index(f"{s_}_lowarm")], P[:, self.jn.index(f"{s_}_wrist")]
            bad |= (self.mesh.distance(E[:, None] + (W - E)[:, None] * u[None, :, None]) < r_fore).any(1)
        return bad

    def mesh_clear(self, win, sides="lr"):
        """Hand points and forearms (frames of win) outside the body mesh (MESH_HAND_CM, MESH_FORE_CM)."""
        from mtcore.mhr import positions
        P = positions(self.ch, win.astype(np.float32))
        u = np.linspace(0.15, 0.9, 5)
        for s_ in sides:
            if (self.mesh.distance(P[:, self.hm.fk.mp21[s_]]) < MESH_HAND_CM).any():
                self.rejects["mesh_hand"] += 1
                return False
            E, W = P[:, self.jn.index(f"{s_}_lowarm")], P[:, self.jn.index(f"{s_}_wrist")]
            F = E[:, None] + (W - E)[:, None] * u[None, :, None]
            if (self.mesh.distance(F) < MESH_FORE_CM[0] + (MESH_FORE_CM[1] - MESH_FORE_CM[0]) * u).any():
                self.rejects["mesh_fore"] += 1
                return False
        return True

    def generate(self, rng, base, T, fps):
        """-> model parameters (T, P) with arms and fingers, segments [{label, variant, t0, t1} ms]. Every
        accepted step (moves between events, events) is checked for interpenetration over its frames."""
        pn = self.pn
        body = np.where([n.startswith("scale_") for n in pn], base, 0.0)
        self.set_body(body)
        pair = tuple(rng.choice(["lap", "desk"], 2))
        mp = seat(rng, pn, np.repeat(body[None], T, 0), fps, self.limits, force_rest=pair, moves=False)
        still_head(mp, pn)
        mp[0] = self.fix_rest(mp[0], rng)  # the starting rest out of the thighs (the keys blend from it)
        keys = {s: [(0, 0, mp[0, self.arm[s]].copy(), np.zeros(len(PARAMS)))] for s in "lr"}
        segs = []
        k = int(rng.uniform(0.3, 1.0) * fps)
        cur = {s: (mp[0, self.arm[s]].copy(), np.zeros(len(PARAMS))) for s in "lr"}
        names, w = list(EVENTS), np.array(list(EVENTS.values()))
        while k < T - int(1.0 * fps):
            m = mp[min(k, T - 1)].copy()
            for s in "lr":
                m[self.arm[s]] = cur[s][0]
            X = self.lm(skeleton_state(self.ch, m)[None])[0]
            self.set_pose(m)
            # between events: both hands to loose neutral poses (a few tries to find a clear move)
            for _ in range(3):
                sol = self._solve(m, {s: self.neutral(rng, X, s) for s in "lr"})
                if not sol:
                    continue
                end = min(T - 1, k + int(rng.uniform(0.8, 1.3) * fps))
                trial = {s: keys[s] + [(k, end, *sol[s])] for s in "lr"}
                if self._clear(mp, trial, T, k, end):
                    keys, cur = trial, {s: sol[s] for s in "lr"}
                    k = end + int(rng.uniform(0.2, 1.0) * fps)
                    break
            kind = names[rng.choice(len(names), p=w / w.sum())]
            accepted = None
            for attempt in range(3):
                slack = float(attempt) if kind in CONTACT else 0.0
                spec_keys = self.event(rng, kind, X, slack)
                if not spec_keys:
                    continue
                self.body_slack = BODY_CONTACT_SLACK_CM if kind in BODY_CONTACT else 0.0
                sols = [self._solve(m, specs, kind in PALM_CHECKED) for _, _, specs in spec_keys]
                self.body_slack = 0.0
                if not all(sols):
                    continue
                trial, kk, c = {s: list(keys[s]) for s in "lr"}, k, dict(cur)
                for (move, hold, _), sol in zip(spec_keys, sols):
                    end = min(T - 1, kk + max(1, int(move * fps)))
                    for s, v in sol.items():
                        trial[s].append((kk, end, *v))
                        c[s] = v
                    kk = end + int(hold * fps)
                    if kk >= T - 1:
                        break
                if self._clear(mp, trial, T, k, kk, CONTACT_OVERLAP_CM if kind in CONTACT else MAX_OVERLAP_CM,
                               BODY_CONTACT_SLACK_CM if kind in BODY_CONTACT else 0.0):
                    accepted = (trial, kk, c)
                    break
            if accepted is None:
                k += int(0.5 * fps)  # nothing clear: let the hands rest a moment
                continue
            t0 = k
            keys, k, cur = accepted
            segs.append({"label": "pair" if kind not in ("turn", "wrist") else kind, "variant": kind,
                         "t0": round(t0 / fps * 1000, 1), "t1": round(min(k, T - 1) / fps * 1000, 1)})
        out = mp.copy()
        t = np.arange(T) / fps
        b = self._blend(keys, T)
        for s in "lr":
            out[:, self.arm[s]] = b[s][0]
            fq = np.clip(b[s][1] + self.hm._idle(rng, t), self.hm.lo, self.hm.hi)
            fq[:, [PARAMS.index(p) for p in UNOBSERVABLE]] = 0.0
            out[:, self.fing[s]] = fq
        out = clamp(pn, out, self.limits)
        out, _, after = self.relaxer(out)  # fingers (and a little of the wrists) pushed out of each other
        self.last_overlap = float(after.max())
        return out, segs
